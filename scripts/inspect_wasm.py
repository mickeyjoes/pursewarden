#!/usr/bin/env python3
"""Fail-closed WASM capability gate for the G1 vault (Phase0_A §1.2, Phase0_E §3.2).

Parses the import, export, type and start sections with the standard library only and
checks them against explicit lists:

* every imported host function must be in ALLOWED_IMPORTS (anything else FAILS, and
  members of the Phase0_A §1.2 denylist are named explicitly);
* exported functions must equal EXPECTED_EXPORTS exactly (plus the linear memory);
* no function type may return more than one value (multi-value is disabled on PV86);
* no start function.

An import check proves absence of a host capability, not correct call arguments; those
are checked from executed receipts by the sandbox tests.

Usage: python3 -I scripts/inspect_wasm.py <contract.wasm> [--json out.json]
Exit status 0 = PASS, 1 = FAIL.
"""
import hashlib
import json
import sys

ALLOWED_IMPORTS = {
    # Promise construction: the single application transfer and the private callback.
    "promise_batch_create",
    "promise_batch_action_transfer",
    "promise_batch_then",
    "promise_batch_action_function_call",
    # Callback input.
    "promise_results_count",
    "promise_result",
    # Registers, context, economics (read-only).
    "read_register",
    "register_len",
    "current_account_id",
    "predecessor_account_id",
    "signer_account_id",
    "input",
    "chain_id",
    "block_index",
    "block_timestamp",
    "epoch_height",
    "storage_usage",
    "account_balance",
    "account_locked_balance",
    "attached_deposit",
    "prepaid_gas",
    "used_gas",
    # Self-state storage.
    "storage_write",
    "storage_read",
    "storage_remove",
    "storage_has_key",
    # Hashing, results, logs, aborts.
    "sha256",
    "value_return",
    "log_utf8",
    "panic",
    "panic_utf8",
}

# Phase0_A §1.2 denylist (nearcore 2.13.4 near-vm-runner/src/imports.rs). Named so a hit is
# reported precisely; any import outside ALLOWED_IMPORTS fails regardless.
DENYLIST = {
    "promise_create", "promise_then", "promise_and", "promise_return",
    "promise_set_refund_to", "refund_to_account_id",
    "promise_batch_action_create_account", "promise_batch_action_deploy_contract",
    "promise_batch_action_deploy_global_contract",
    "promise_batch_action_deploy_global_contract_by_account_id",
    "promise_batch_action_use_global_contract",
    "promise_batch_action_use_global_contract_by_account_id",
    "promise_batch_action_function_call_weight", "promise_batch_action_stake",
    "promise_batch_action_add_key_with_full_access",
    "promise_batch_action_add_key_with_function_call",
    "promise_batch_action_delete_key", "promise_batch_action_delete_account",
    "promise_batch_action_transfer_to_gas_key",
    "promise_batch_action_add_gas_key_with_full_access",
    "promise_batch_action_add_gas_key_with_function_call",
    "promise_batch_action_state_init", "promise_batch_action_state_init_by_account_id",
    "set_state_init_data_entry",
    "promise_yield_create", "promise_yield_create_with_id",
    "promise_yield_resume", "promise_yield_resume_with_yield_id",
}

EXPECTED_EXPORTS = {
    "new", "request_payment", "on_payment_result", "freeze",
    "get_mandate", "get_request", "get_admissions",
    # Always generated by near-sdk 5.29.1 for #[near(contract_state)] (NEP-330 view).
    "contract_source_metadata",
}

# LLVM's wasm-ld exports these memory-layout markers. They are data, not entrypoints; they
# are accepted only by exact name and only if the exported global is immutable.
ALLOWED_GLOBAL_EXPORTS = {"__data_end", "__heap_base"}

KIND = {0: "func", 1: "table", 2: "memory", 3: "global", 4: "tag"}


class Reader:
    def __init__(self, data, pos=0, end=None):
        self.d, self.p, self.end = data, pos, len(data) if end is None else end

    def byte(self):
        if self.p >= self.end:
            raise ValueError("truncated")
        b = self.d[self.p]
        self.p += 1
        return b

    def uleb(self):
        result = shift = 0
        while True:
            b = self.byte()
            result |= (b & 0x7F) << shift
            shift += 7
            if not b & 0x80:
                return result
            if shift > 35:
                raise ValueError("leb128 too long")

    def name(self):
        n = self.uleb()
        s = self.d[self.p:self.p + n]
        if len(s) != n:
            raise ValueError("truncated name")
        self.p += n
        return s.decode("utf-8")

    def sleb(self):
        result = shift = 0
        while True:
            b = self.byte()
            result |= (b & 0x7F) << shift
            shift += 7
            if not b & 0x80:
                if b & 0x40:
                    result -= 1 << shift
                return result
            if shift > 70:
                raise ValueError("leb128 too long")

    def const_expr(self):
        """Skip a constant init expression; supports the opcodes LLVM emits for globals."""
        while True:
            op = self.byte()
            if op == 0x0B:
                return
            if op in (0x41, 0x42):
                self.sleb()
            elif op == 0x23:
                self.uleb()
            else:
                raise ValueError(f"unsupported init opcode {op:#x}")

    def limits(self):
        flag = self.byte()
        lo = self.uleb()
        hi = self.uleb() if flag & 1 else None
        return lo, hi


def parse(data):
    if data[:4] != b"\0asm" or data[4:8] != b"\x01\0\0\0":
        raise ValueError("not a wasm v1 module")
    r = Reader(data, 8)
    out = {"sections": [], "types": [], "imports": [], "exports": [], "start": None, "globals": []}
    while r.p < len(data):
        sid = r.byte()
        size = r.uleb()
        body = Reader(data, r.p, r.p + size)
        out["sections"].append({"id": sid, "size": size})
        if sid == 1:
            for _ in range(body.uleb()):
                form = body.byte()
                if form != 0x60:
                    raise ValueError(f"unexpected type form {form:#x}")
                params = [body.byte() for _ in range(body.uleb())]
                results = [body.byte() for _ in range(body.uleb())]
                out["types"].append({"params": len(params), "results": len(results)})
        elif sid == 2:
            for _ in range(body.uleb()):
                mod, field, kind = body.name(), body.name(), body.byte()
                if kind == 0:
                    desc = {"type": body.uleb()}
                elif kind == 1:
                    desc = {"reftype": body.byte(), "limits": body.limits()}
                elif kind == 2:
                    desc = {"limits": body.limits()}
                elif kind == 3:
                    desc = {"valtype": body.byte(), "mut": body.byte()}
                else:
                    raise ValueError(f"unsupported import kind {kind}")
                out["imports"].append({"module": mod, "name": field, "kind": KIND[kind], **desc})
        elif sid == 6:
            for _ in range(body.uleb()):
                valtype, mut = body.byte(), body.byte()
                body.const_expr()
                out["globals"].append({"valtype": valtype, "mutable": bool(mut)})
        elif sid == 7:
            for _ in range(body.uleb()):
                name, kind, idx = body.name(), body.byte(), body.uleb()
                out["exports"].append({"name": name, "kind": KIND.get(kind, str(kind)), "index": idx})
        elif sid == 8:
            out["start"] = body.uleb()
        r.p += size
    return out


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    path = argv[1]
    data = open(path, "rb").read()
    info = parse(data)
    failures = []

    func_imports = [i for i in info["imports"] if i["kind"] == "func"]
    other_imports = [i for i in info["imports"] if i["kind"] != "func"]
    for i in func_imports:
        if i["module"] != "env":
            failures.append(f"import from unexpected module {i['module']}.{i['name']}")
        elif i["name"] in DENYLIST:
            failures.append(f"DENYLISTED import env.{i['name']}")
        elif i["name"] not in ALLOWED_IMPORTS:
            failures.append(f"import env.{i['name']} not in allowlist (review required)")
    for i in other_imports:
        failures.append(f"non-function import {i['module']}.{i['name']} ({i['kind']})")

    func_exports = {e["name"] for e in info["exports"] if e["kind"] == "func"}
    other_exports = [e for e in info["exports"] if e["kind"] != "func"]
    for name in sorted(func_exports - EXPECTED_EXPORTS):
        failures.append(f"unexpected callable export {name}")
    for name in sorted(EXPECTED_EXPORTS - func_exports):
        failures.append(f"missing expected export {name}")
    imported_globals = sum(1 for i in info["imports"] if i["kind"] == "global")
    for e in other_exports:
        if e["kind"] == "memory" and e["name"] == "memory":
            continue
        if e["kind"] == "global" and e["name"] in ALLOWED_GLOBAL_EXPORTS:
            local = e["index"] - imported_globals
            if 0 <= local < len(info["globals"]) and not info["globals"][local]["mutable"]:
                continue
            failures.append(f"layout global {e['name']} is mutable or unresolved")
            continue
        failures.append(f"unexpected non-function export {e['name']} ({e['kind']})")

    multi = [i for i, t in enumerate(info["types"]) if t["results"] > 1]
    if multi:
        failures.append(f"multi-value function types present: {multi}")
    if info["start"] is not None:
        failures.append(f"start function present: {info['start']}")

    report = {
        "file": path,
        "size_bytes": len(data),
        "sha256_hex": hashlib.sha256(data).hexdigest(),
        "imports": sorted(f"{i['module']}.{i['name']}" for i in info["imports"]),
        "exports": sorted(f"{e['name']}:{e['kind']}" for e in info["exports"]),
        "type_count": len(info["types"]),
        "globals": info["globals"],
        "section_ids": [s["id"] for s in info["sections"]],
        "denylist_checked": sorted(DENYLIST),
        "allowlist": sorted(ALLOWED_IMPORTS),
        "failures": failures,
        "verdict": "PASS" if not failures else "FAIL",
    }
    text = json.dumps(report, indent=2)
    if "--json" in argv:
        with open(argv[argv.index("--json") + 1], "w") as f:
            f.write(text + "\n")
    print(text)
    return 0 if not failures else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
